PHASES=frozenset({'legacy_seed','native_seed','proposal_admission','waiting_run','receipt_barrier',
    'completed_run','uncertain_effect_barrier','original_capture','capture_validation','seed_counters',
    'logical_backup','new_database','logical_restore','deliver_configuration','fresh_replica','readiness',
    'legacy_verification','restored_capture','journal_claims','native_verification','evaluation'})
CAPTURE_FIELDS=('proposals','reservations','native_runs','snapshots','receipts','views','usage','journal','domain')
CATEGORIES=frozenset({'invalid_fixture','http_failure','database_failure','engine_failure','timeout',
    'unexpected_failure','capture_shape','proposal_identity','reservation_identity','snapshot_contract',
    'receipt_integrity','journal_contract','domain_contract',
    *(name+'_count' for name in CAPTURE_FIELDS),*(name+'_identity' for name in CAPTURE_FIELDS)})


class NativeRestoreFailure(ValueError):
    """A closed diagnostic that never carries arbitrary exception text/state."""
    def __init__(self,phase,category):
        if phase not in PHASES or category not in CATEGORIES:raise ValueError('invalid native restore diagnostic')
        self._phase,self._category=phase,category
        super().__init__('populated native restore evidence required' if phase=='capture_validation'
            else 'native restore fixture failed')

    @property
    def diagnostic(self):
        return {'phase':self._phase,'category':self._category}


def failure(phase,error):
    """Classify only exception types; never inspect messages or HTTP bodies."""
    from .stack import EngineError
    if isinstance(error,NativeRestoreFailure):return error
    category=('http_failure' if isinstance(error,httpx.HTTPError) else
        'database_failure' if isinstance(error,psycopg.Error) else
        'engine_failure' if isinstance(error,EngineError) else
        'timeout' if isinstance(error,(TimeoutError,subprocess.TimeoutExpired)) else
        'invalid_fixture' if isinstance(error,(ValueError,KeyError,TypeError)) else 'unexpected_failure')
    return NativeRestoreFailure(phase,category)


@contextmanager
def phase(name):
    try:yield
    except Exception as error:raise failure(name,error) from None


def _headers(config, other=False):
    return {'Authorization':'Bearer '+list(config['principals'])[int(other)]}


def _get(client, url, headers):
    response=client.get(url,headers=headers)
    response.raise_for_status()
    return response.json()


def _post(client, config, path, body, *, key=None):
    response=client.post(config['a']+path,headers={**_headers(config),
        'Idempotency-Key':key or uuid.uuid4().hex},json=body,timeout=35)
    response.raise_for_status()
    return response.json()


def _control(config,client,**settings):
    client.post(config['model']+'/control',json={'preserve_allowance':True,**settings}).raise_for_status()


def _stats(config,client):
    return _get(client,config['model']+'/stats',{})


def _crash(stack,config,client,proposal,entity,*,barrier,settings):
    """Kill only verified A after the durable receipt or domain-effect barrier."""
    _control(config,client,**settings)
    before=_stats(config,client)
    key=uuid.uuid4().hex
    def submit():
        try:
            return _post(client,config,'/native-runs',{'proposal_id':proposal['proposal_id'],
                'inputs':{'entity_id':entity}},key=key)
        except httpx.HTTPError:
            return None
    killed=False
    with ThreadPoolExecutor(max_workers=1) as pool:
        future=pool.submit(submit)
        try:
            deadline=time.monotonic()+10
            while True:
                observed=_stats(config,client)
                reached=(observed['accepted_events']>before['accepted_events'] if barrier=='accepted_events'
                    else observed['barriers'][barrier]>before['barriers'][barrier])
                if reached:break
                if time.monotonic()>=deadline:raise ValueError('native restore barrier timeout')
                time.sleep(.05)
            with psycopg.connect(config['migration_dsn'],connect_timeout=5,options='-c statement_timeout=5000') as connection:
                row=connection.execute('SELECT run_id FROM lab_app.runs WHERE idempotency_key=%s',(key,)).fetchone()
                if row is None:raise ValueError('native restore reservation missing')
                run_id=row[0]
                # The accepted event follows durable save_receipt. The effect
                # event follows the domain transaction but precedes journal commit.
                if barrier=='accepted_events':
                    ready=connection.execute('SELECT count(*) FROM prosaic_harness.receipts WHERE run_id=%s',(run_id,)).fetchone()[0]==1
                else:
                    ready=(connection.execute('SELECT count(*) FROM lab_fixture.effects WHERE business_key=%s',(entity,)).fetchone()[0]==1 and
                        connection.execute('SELECT state FROM lab_app.tool_operations WHERE operation_key=%s',(entity,)).fetchall()==[('uncertain',)])
                if not ready:raise ValueError('native restore durable barrier missing')
            identifier=stack.manifest['replica_ids']['a']
            validate_resource(json.loads(command(stack.engine,'inspect',identifier))[0],identifier,stack.owner)
            command(stack.engine,'kill',identifier)
            killed=True
        finally:
            _control(config,client,scenario=settings['scenario'])
            future.result(timeout=10)
            if killed:
                fresh='seed-a-'+uuid.uuid4().hex
                config['a']=stack.start_replica(fresh)
                stack.manifest['replica_ids']['a']=stack.manifest['replica_ids'][fresh]
                stack.manifest['endpoints']['a']=config['a']
                stack._save()
    return run_id


def capture(config,run_ids,proposal_ids,client):
    """Read complete row contracts and filtered owner views into private memory."""
    captured={}
    with psycopg.connect(config['migration_dsn'],connect_timeout=5,options='-c statement_timeout=5000') as connection:
        connection.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
        # All identifiers are bound parameters; these fixed tables are public
        # storage contracts owned by the application and installed adapters.
        queries={
            'proposals':('SELECT row_to_json(t) FROM lab_app.proposals t WHERE proposal_id=ANY(%s) ORDER BY proposal_id',proposal_ids),
            'reservations':('SELECT row_to_json(t) FROM lab_app.runs t WHERE run_id=ANY(%s) ORDER BY run_id',run_ids),
            'native_runs':('SELECT row_to_json(t) FROM lab_app.native_runs t WHERE run_id=ANY(%s) ORDER BY run_id',run_ids),
            'snapshots':('SELECT row_to_json(t) FROM prosaic_harness.runs t WHERE run_id=ANY(%s) ORDER BY run_id',run_ids),
            'receipts':('SELECT row_to_json(t) FROM prosaic_harness.receipts t WHERE run_id=ANY(%s) ORDER BY run_id,invocation_id',run_ids),
            'journal':('''SELECT row_to_json(t) FROM lab_app.tool_operations t WHERE operation_key IN
                (SELECT request->'inputs'->>'entity_id' FROM lab_app.runs WHERE run_id=ANY(%s))
                ORDER BY operation_namespace,operation_key''',run_ids),
            'domain':('''SELECT row_to_json(t) FROM lab_fixture.effects t WHERE business_key IN
                (SELECT request->'inputs'->>'entity_id' FROM lab_app.runs WHERE run_id=ANY(%s))
                ORDER BY namespace,business_key''',run_ids)}
        for name,(query,ids) in queries.items():
            captured[name]=[row[0] for row in connection.execute(query,(ids,))]
    captured['views']=[_get(client,config['b']+'/runs/'+identifier,_headers(config)) for identifier in run_ids]
    captured['usage']=[accounting_snapshot(_get(client,config['b']+'/runs/'+identifier+'/usage',_headers(config)))
        for identifier in run_ids]
    # Encode/decode cuts any aliases to mutable HTTP/adapter return values and
    # enforces one aggregate bound. This witness is never serialized publicly.
    encoded=json.dumps(captured,ensure_ascii=False,allow_nan=False)
    if len(encoded.encode())>16*1024*1024:raise ValueError('native restore evidence bound exceeded')
    return json.loads(encoded)


def validate_capture(captured,run_ids,proposal_ids):
    """A matching empty dump is insufficient evidence of native restoration."""
    def invalid(category):raise NativeRestoreFailure('capture_validation',category)
    sizes={'proposals':3,'reservations':4,'native_runs':4,'snapshots':4,'receipts':4,
        'views':4,'usage':4,'journal':2,'domain':2}
    if (type(captured) is not dict or set(captured)!=set(sizes) or len(set(run_ids))!=4 or
        len(set(proposal_ids))!=3):invalid('capture_shape')
    for key,size in sizes.items():
        if type(captured[key]) is not list or len(captured[key])!=size:invalid(key+'_count')
    for field,identifier,expected in (('proposals','proposal_id',proposal_ids),
            ('reservations','run_id',run_ids),('native_runs','run_id',run_ids),('snapshots','run_id',run_ids),('views','run_id',run_ids)):
        if any(type(row) is not dict for row in captured[field]) or {row.get(identifier) for row in captured[field]}!=set(expected):invalid(field+'_identity')
    proposals={row['proposal_id']:row for row in captured['proposals']}
    reservations={row['run_id']:row for row in captured['reservations']}
    for row in captured['proposals']:
        reference=row.get('reference',{})
        if (not row.get('proposal_json') or not reference or
            row.get('policy_digest')!=row.get('bundle_identity') or
            hashlib.sha256(row['proposal_json'].encode()).hexdigest()!=row.get('request_digest') or
            any(reference.get(key)!=row.get(column) for key,column in (
                ('bundleVersion','bundle_version'),('bundleIdentity','bundle_identity'),
                ('proposalSha256','request_digest'),('workflowFingerprint','workflow_fingerprint')))):invalid('proposal_identity')
    for link in captured['native_runs']:
        row=reservations[link['run_id']]
        proposal=proposals.get(link.get('proposal_id'))
        if (proposal is None or row.get('workflow')!='native' or not row.get('namespace') or not row.get('environment') or
            row.get('assets_hash')!=proposal['bundle_identity'] or
            row.get('request',{}).get('proposal_id')!=link['proposal_id'] or
            any(row.get(key)!=proposal.get(key) or row.get(key)!=link.get(key) for key in ('tenant_id','actor_id')) or
            not row.get('billing_account_id')):invalid('reservation_identity')
    for row in captured['snapshots']:
        if not row.get('document') or type(row.get('revision')) is not int or row['revision']<1:invalid('snapshot_contract')
        try:json.loads(row['document'])
        except (ValueError,TypeError):invalid('snapshot_contract')
    for row in captured['receipts']:
        if (row.get('run_id') not in run_ids or not row.get('document') or
            hashlib.sha256(row['document'].encode()).hexdigest()!=row.get('sha256')):invalid('receipt_integrity')
    if ({row.get('state') for row in captured['journal']}!={'completed','uncertain'} or
        any(type(row.get('signature')) is not str or len(row['signature'])!=64 or
            not row.get('claim_token') or (row['state']=='uncertain' and row.get('outcome') is not None) or
            (row['state']=='completed' and row.get('outcome')!={'status':'ok','result':{'applied':True}})
            for row in captured['journal'])):invalid('journal_contract')
    if any(row.get('amount')!=1 for row in captured['domain']):invalid('domain_contract')


def seed(stack,config,client):
    """Generate four distinct states with six native calls and three proposals."""
    before=_stats(config,client)
    _control(config,client,scenario='native')
    with phase('proposal_admission'):
        composed=_post(client,config,'/workflow-proposals',approved_proposal())
        receipt=_post(client,config,'/workflow-proposals',{'definition':{'version':1,'start':'find','steps':{
            'find':{'kind':'agent','agent':'finder','schema':'found','next':'done'},
            'done':{'kind':'finish','requires':['find']}}}})
        effect=_post(client,config,'/workflow-proposals',effect_proposal())
    entities={name:uuid.uuid4().hex for name in ('waiting','receipt','completed','uncertain')}
    with phase('waiting_run'):
        waiting=_post(client,config,'/native-runs',{'proposal_id':composed['proposal_id'],'inputs':{'entity_id':entities['waiting']}})
        if (waiting.get('status')!='waiting' or not waiting.get('interaction',{}).get('responseSchema') or
            waiting['interaction'].get('reviewOutputs')!={'review':{'entity_id':entities['waiting'],'approved':True}}):
            raise ValueError('native restore structured approval missing')
    with phase('receipt_barrier'):
        saved=_crash(stack,config,client,receipt,entities['receipt'],barrier='accepted_events',
            settings={'scenario':'native','accepted_gate':True})
    _control(config,client,scenario='native_effect')
    with phase('completed_run'):
        completed=_post(client,config,'/native-runs',{'proposal_id':effect['proposal_id'],'inputs':{'entity_id':entities['completed']}})
        if completed.get('status')!='completed':raise ValueError('native restore completed effect missing')
    with phase('uncertain_effect_barrier'):
        uncertain=_crash(stack,config,client,effect,entities['uncertain'],barrier='tool-effect',
            settings={'scenario':'native_effect','effect_gate':'tool-effect'})
    run_ids=[waiting['run_id'],saved,completed['run_id'],uncertain]
    proposal_ids=[composed['proposal_id'],receipt['proposal_id'],effect['proposal_id']]
    with phase('original_capture'):captured=capture(config,run_ids,proposal_ids,client)
    with phase('capture_validation'):validate_capture(captured,run_ids,proposal_ids)
    with phase('seed_counters'):
        after=_stats(config,client)
        if (after['calls']!=before['calls']+6 or
            after['barriers']['tool-handler']!=before['barriers']['tool-handler']+2):
            raise ValueError('native restore fixture counters disagree')
    return {'capture':captured,'run_ids':run_ids,'proposal_ids':proposal_ids,
        'calls_before':after['calls'],'handlers_before':after['barriers']['tool-handler']}


def verify(config,fixture,client):
    """Read restored state and claim existing journal rows without executing runs."""
    from prosaic_integration_lab.tool_journal import PgToolJournal
    original=fixture['capture']
    with phase('restored_capture'):restored=capture(config,fixture['run_ids'],fixture['proposal_ids'],client)
    equal={name:original.get(name)==restored.get(name) for name in original}
    result={'proposal_verified':equal.get('proposals',False),
        'reference_verified':equal.get('proposals',False),'bundle_verified':equal.get('proposals',False),
        'reservation_verified':equal.get('reservations',False) and equal.get('native_runs',False),
        'snapshot_verified':equal.get('snapshots',False),'receipt_document_verified':equal.get('receipts',False),
        'interaction_verified':equal.get('views',False),'native_usage_verified':equal.get('usage',False),
        'journal_verified':equal.get('journal',False),'domain_verified':equal.get('domain',False),
        'completed_claim_verified':False,'uncertain_claim_verified':False,'owner_verified':True}
    try:
        validate_capture(original,fixture['run_ids'],fixture['proposal_ids'])
        validate_capture(restored,fixture['run_ids'],fixture['proposal_ids'])
        journal=PgToolJournal(config['app_dsn'],identity='fixture-journal-v1')
        for row in restored['journal']:
            claim=journal.claim(row['operation_namespace'],row['operation_key'],row['signature'])
            if row['state']=='completed':
                result['completed_claim_verified']=(claim.state=='replay' and claim.claim_token is None and
                    claim.signature==row['signature'] and claim.outcome==row['outcome'])
            else:
                result['uncertain_claim_verified']=(claim.state=='uncertain' and claim.claim_token is None and
                    claim.signature==row['signature'] and claim.outcome is None)
        # Claims must preserve signatures, original fencing tokens and outcomes.
        result['journal_verified'] &= capture(config,fixture['run_ids'],fixture['proposal_ids'],client)['journal']==original['journal']
    except (ValueError,KeyError,TypeError):
        result['completed_claim_verified']=result['uncertain_claim_verified']=False
    for identifier in fixture['run_ids']:
        for suffix in ('','/usage'):
            result['owner_verified'] &= client.get(config['b']+'/runs/'+identifier+suffix,
                headers=_headers(config,other=True)).status_code==404
    after=_stats(config,client)
    result.update(native_runs=4,native_proposals=3,calls_before=fixture['calls_before'],calls_after=after['calls'],
        handlers_before=fixture['handlers_before'],handlers_after=after['barriers']['tool-handler'])
    result['native_verified']=(all(result[name] is True for name in result if name.endswith('_verified')) and
        result['calls_before']==result['calls_after'] and result['handlers_before']==result['handlers_after'])
    return result
